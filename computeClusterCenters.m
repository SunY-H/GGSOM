function centers = computeClusterCenters(X, Xiajinsi)
    % X是数据矩阵，每一行是一个样本，每一列是一个特征
    % Xiajinsi是下近似矩阵，每一行对应一个类别的下近似度 
    % Xiajinsi 矩阵的每一行代表一个决策类（或聚类）中各个样本的下近似度。这个矩阵给出了每个类别相对于每个样本的模糊相似度的下近似。
    % 然而，将这些下近似度直接用作初始节点的权重向量可能不是最直接的方法，因为这些值代表的是样本到类别的归属程度，而不是特征空间中的点。

% 为了使用下近似中心作为初始权重，我们应该首先从Xiajinsi矩阵中提取或计算出可以代表每个类别的中心向量。这可以通过以下步骤完成：

% 计算每个类别的代表中心：

% 对于每个类别（Xiajinsi矩阵的每一行），计算属于该类别的样本的加权平均向量，其中权重由下近似度给出。
% 这可以通过将每个样本的特征向量与其对应的下近似度相乘，然后对整个类别求和并标准化来实现。
% 使用这些中心向量作为初始权重：
% 
% 当初始化GSOM网络中的节点时，可以将这些计算出的聚类中心向量直接用作节点的初始权重。
% 具体来说，你可以按照以下步骤操作：
% 
% 计算每个类别的加权中心：对于Xiajinsi矩阵中的每一行（每个类别），计算所有样本的加权平均，权重即为该行的下近似值。
% 将这些加权中心作为GSOM节点的初始权重。
% 这种方法能够确保GSOM的初始节点更接近数据集中的实际聚类中心，从而可能提高网络训练的效率和有效性。

    [numClasses, ~] = size(Xiajinsi);
    numFeatures = size(X, 2);
    centers = zeros(numClasses, numFeatures);

    for k = 1:numClasses
        % 计算每个类别的加权中心
        sumWeights = sum(Xiajinsi(k, :)); % 计算了所有样本对于类别k的隶属度的总和，这个总和作为归一化的分母，确保加权平均是标准化的
        for j = 1:numFeatures
            weightedSum = sum(X(:, j) .* Xiajinsi(k, :)'); % 对于每个特征j计算所有样本的特征值xij与其对应类别k的隶属度aik的乘积之和。使用点乘来同时考虑所有样本对该特征的贡献
            centers(k, j) = weightedSum / sumWeights; % 将加权和除以权重总和得到归一化的加权中心。这意味着每个类别的特征中心是由属于该类别的所有样本的特征值根据其隶属度加权平均得到的
        end
    end

    % 通过这种方法，计算得到的centers矩阵为每个类别提供了一个代表性的特征向量，这些向量可以作为初始化GGSOM时的节点权重，这样的处理能有效地捕捉到每个类别在特征空间的中心位置，
    % 特别是在处理模糊分类和模糊隶属度时。

end